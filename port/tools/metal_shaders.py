"""Mac build (finding 075): port/gs/raster.hlsl's shaders as one Metal library.

    python port/tools/metal_shaders.py          writes build/port-mac/shaders/shaders.h

Each entry point the renderers compile (gpu.c, gpu_native.inc) goes HLSL -> SPIR-V (glslang) ->
Metal Shading Language (spirv-cross) -> AIR (the Metal compiler); the AIR files are linked into
one metallib, embedded in the Mac program as bytes (port/mac/native/metal.m). Resource bindings
follow the HLSL register: b# is buffer #, t# buffer or texture 8 + #, u# buffer or texture
TEXTURE_UAV + #, s# sampler #; metal.m binds by the same rule.

D3DCompile's defines can't change on the Mac: the exact renderer's options are the defaults
(early depth, address shift and exclusive word store on), and its double-precision depth runs
in float (raster.hlsl DHD_NO_DOUBLE). gpu.c's hardware rasterizer (DHD_HARDWARE_PIXEL) needs
rasterizer-ordered views and is not built: the Mac reports no such feature.

Needs glslang, spirv-cross (brew install glslang spirv-cross) and Xcode's Metal compiler."""
import os, re, shutil, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE = os.path.join(ROOT, 'port', 'gs', 'raster.hlsl')
OUT = os.path.join(ROOT, 'build', 'port-mac', 'shaders')
TEXTURE_SRV, TEXTURE_UAV = 8, 24

NATIVE = ['-DDHD_NATIVE=1']
EXACT = ['-DDHD_EARLY_DEPTH=1', '-DDHD_ADDRESS_SHIFT=1', '-DDHD_EXCLUSIVE_WORD_STORE=1', '-DDHD_NO_DOUBLE=1']
# (Metal function name, HLSL entry, stage, defines): the name is what D3DCompile's entry becomes
SHADERS = [
    ('native_vertex', 'native_vertex', 'vert', NATIVE), ('native_pixel', 'native_pixel', 'frag', NATIVE),
    ('native_scanout', 'native_scanout', 'comp', NATIVE), ('native_convert', 'native_convert', 'comp', NATIVE),
    ('present_vertex', 'present_vertex', 'vert', NATIVE), ('present_pixel', 'present_pixel', 'frag', NATIVE),
    ('native_blit', 'native_blit', 'frag', NATIVE), ('native_upload_alpha', 'native_upload_alpha', 'frag', NATIVE),
    ('exact_main', 'main', 'comp', EXACT), ('exact_scanout', 'scanout', 'comp', EXACT),
    ('exact_local_copy', 'local_copy', 'comp', EXACT),
]


def run(cmd, cwd=None):
    p = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if p.returncode:
        sys.exit('%s:\n%s%s' % (' '.join(cmd), p.stdout[-3000:], p.stderr[-3000:]))
    return p


def tool(name):
    path = shutil.which(name)
    if not path:
        sys.exit('%s not found: brew install glslang spirv-cross' % name)
    return path


def threadgroups(source):
    """{entry: (x, y, z)} of the compute entries' [numthreads]."""
    out = {}
    for m in re.finditer(r'\[numthreads\((\d+),\s*(\d+),\s*(\d+)\)\]\s*\w+\s+(\w+)\s*\(', source):
        out[m.group(4)] = tuple(int(m.group(i)) for i in (1, 2, 3))
    return out


def build():
    os.makedirs(OUT, exist_ok=True)
    source = open(SOURCE, encoding='utf-8').read()
    groups = threadgroups(source)
    # the tools get plain file names: the checkout's path may hold spaces
    shutil.copyfile(SOURCE, os.path.join(OUT, 'raster.hlsl'))
    shift = ['--hlsl-iomap', '--shift-cbuffer-binding', '0', '--shift-texture-binding', str(TEXTURE_SRV),
             '--shift-UAV-binding', str(TEXTURE_UAV), '--shift-sampler-binding', '0']
    airs = []
    for name, entry, stage, defines in SHADERS:
        run([tool('glslangValidator'), '-D', '-V', '-S', stage, '-e', entry, '--target-env', 'vulkan1.1', *shift,
             *defines, '-o', name + '.spv', 'raster.hlsl'], cwd=OUT)
        run([tool('spirv-cross'), '--msl', '--msl-version', '20300', '--msl-decoration-binding',
             '--rename-entry-point', entry, name, stage, name + '.spv', '--output', name + '.metal'], cwd=OUT)
        if name == 'native_pixel':  # SV_Target1 is the blend's second source (SRC1_ALPHA): Metal's index 1
            path = os.path.join(OUT, name + '.metal')
            msl = open(path, encoding='utf-8').read()
            if msl.count('[[color(1)]]') != 1:
                sys.exit('native_pixel.metal: no single second colour output to make the blend source')
            open(path, 'w', encoding='utf-8').write(msl.replace('[[color(1)]]', '[[color(0), index(1)]]'))
        run(['xcrun', '-sdk', 'macosx', 'metal', '-c', '-O2', name + '.metal', '-o', name + '.air'], cwd=OUT)
        airs.append(name + '.air')
    run(['xcrun', '-sdk', 'macosx', 'metallib', *airs, '-o', 'shaders.metallib'], cwd=OUT)
    data = open(os.path.join(OUT, 'shaders.metallib'), 'rb').read()
    lines = ['/* Generated by port/tools/metal_shaders.py from port/gs/raster.hlsl: do not edit. */',
             'static const unsigned char shader_library[] = {']
    for i in range(0, len(data), 24):
        lines.append(''.join('%d,' % b for b in data[i:i + 24]))
    lines += ['};', 'static const struct { const char *entry, *name; unsigned threads[3]; } shader_entries[] = {']
    for name, entry, stage, defines in SHADERS:
        x, y, z = groups.get(entry, (1, 1, 1))
        kind = 'native' if defines is NATIVE else 'exact'
        lines.append('    {"%s:%s", "%s", {%d, %d, %d}},' % (kind, entry, name, x, y, z))
    lines += ['};', '#define TEXTURE_SRV %d' % TEXTURE_SRV, '#define TEXTURE_UAV %d' % TEXTURE_UAV, '']
    with open(os.path.join(OUT, 'shaders.h'), 'w', newline='\n') as f:
        f.write('\n'.join(lines))
    return os.path.join(OUT, 'shaders.h')


if __name__ == '__main__':
    print(build())
